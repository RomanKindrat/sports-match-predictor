export function createT(lang) {
  const dict = I18N[lang] || I18N.en
  return (key, vars = {}) => {
    const template = dict[key] ?? I18N.en[key] ?? key
    return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
  }
}
