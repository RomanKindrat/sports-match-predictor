export const I18N = {
  uk: UA,
  en: UA,
}

export function createT(lang) {
  const dict = I18N[lang] || I18N.uk
  return (key, vars = {}) => {
    const template = dict[key] ?? I18N.uk[key] ?? key
    return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
  }
}
